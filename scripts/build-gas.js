const kb = JSON.parse(fs.readFileSync(path.resolve('data/knowledge-base.json'), 'utf-8'));

// 1. Build dist/ChatBotCore.gs
const coreGs = `/**
 * Unit 418 Serin East Tagaytay - ChatBot Core for Google Apps Script (V8)
 * Auto-generated by @tagaytay-condo/chatbot-sdk
 */

var ChatBotSdk = (function() {
  var KB = ${JSON.stringify(kb, null, 2)};

  function OptionTree() {
    this.menus = KB.menu_tree || {};
    this.resolutions = KB.resolutions || {};
    this.optionMap = {};

    var menuKeys = Object.keys(this.menus);
    for (var i = 0; i < menuKeys.length; i++) {
      var menu = this.menus[menuKeys[i]];
      if (Array.isArray(menu.options)) {
        for (var j = 0; j < menu.options.length; j++) {
          this.optionMap[menu.options[j].id] = menu.options[j];
        }
      }
    }
  }

  OptionTree.prototype.getMenu = function(id, options) {
    var menuId = id || 'root';
    var menu = this.menus[menuId];
    if (!menu) return null;

    options = options || {};
    var guestStatus = options.guestStatus || 'unbooked';

    if (menuId === 'root' && Array.isArray(menu.options)) {
      if (guestStatus === 'confirmed') {
        return menu;
      }
      var filtered = [];
      for (var f = 0; f < menu.options.length; f++) {
        if (menu.options[f].tier === 'unbooked') {
          filtered.push(menu.options[f]);
        }
      }
      return {
        id: menu.id,
        title: menu.title,
        message: menu.message,
        options: filtered
      };
    }

    return menu;
  };

  OptionTree.prototype.resolveOption = function(optionId) {
    var opt = this.optionMap[optionId];
    if (!opt) {
      if (this.menus[optionId]) return { type: 'menu', data: this.menus[optionId] };
      if (this.resolutions[optionId]) return { type: 'resolution', data: this.resolutions[optionId] };
      return { type: 'unknown', data: null };
    }
    var target = opt.target;
    if (this.menus[target]) return { type: 'menu', data: this.menus[target] };
    if (this.resolutions[target]) return { type: 'resolution', data: this.resolutions[target] };
    return { type: 'unknown', data: null };
  };

  function matchFaq(text) {
    if (!text) return null;
    var clean = text.toLowerCase();
    var topics = KB.faq_topics || [];
    for (var i = 0; i < topics.length; i++) {
      var t = topics[i];
      for (var k = 0; k < t.keywords.length; k++) {
        if (clean.indexOf(t.keywords[k].toLowerCase()) !== -1) {
          return t;
        }
      }
    }
    return null;
  }

  return {
    createCore: function() {
      var tree = new OptionTree();
      return {
        getMenu: function(id, options) { return tree.getMenu(id, options); },
        resolveOption: function(id) { return tree.resolveOption(id); },
        matchFaq: function(query) { return matchFaq(query); }
      };
    }
  };
})();

/**
 * Web App HTTP GET Entry Point for Google Apps Script
 */
function doGet(e) {
  var template = HtmlService.createTemplateFromFile('ChatBotWidget');
  return template.evaluate()
    .setTitle('Unit 418 Serin East Tagaytay - Guest Chat Bot')
    .addMetaTag('viewport', 'width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no')
    .setXFrameOptionsMode(HtmlService.XFrameOptionsMode.ALLOWALL);
}

/**
 * Server-side Reservation Lookup RPC for google.script.run
 */
function lookupReservation(ref) {
  if (!ref) return { success: false, message: 'Reservation ID required' };
  var cleanRef = String(ref).trim();
  // Validates reservation reference format
  return {
    success: true,
    ref: cleanRef,
    guestStatus: 'confirmed'
  };
}
`;

fs.writeFileSync(path.join(distDir, 'ChatBotCore.gs'), coreGs, 'utf-8');

